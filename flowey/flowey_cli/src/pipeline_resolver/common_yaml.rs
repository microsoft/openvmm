const GITHUB_WORKFLOW_MAX_BYTES: usize = 500 * 1024;
const ADO_YAML_MAX_BYTES: usize = 512 * 1024;
pub(super) const GENERATED_YAML_HEADER: &str = "\
##############################
# THIS FILE IS AUTOGENERATED #
#    DO NOT MANUALLY EDIT    #
##############################
";

fn check_generated_yaml_size(
    yaml: &str,
    backend: FlowBackendCli,
    pipeline_file: &Path,
) -> anyhow::Result<()> {
    if matches!(backend, FlowBackendCli::Github) && yaml.len() > GITHUB_WORKFLOW_MAX_BYTES {
        anyhow::bail!(
            "GitHub workflow '{}' is {} bytes, exceeding the 500 KB ({} byte) limit. Reduce the generated workflow size.",
            pipeline_file.display(),
            yaml.len(),
            GITHUB_WORKFLOW_MAX_BYTES,
        );
    }

    if matches!(backend, FlowBackendCli::Ado) && yaml.len() > ADO_YAML_MAX_BYTES {
        anyhow::bail!(
            "Azure DevOps YAML '{}' is {} bytes, exceeding the {} byte file limit. Enable `Pipeline::ado_use_job_templates`, or reduce the size of an individual job or the pipeline metadata.",
            pipeline_file.display(),
            yaml.len(),
            ADO_YAML_MAX_BYTES,
        );
    }

    Ok(())
}

pub(super) fn serialize_yaml(value: &Value) -> anyhow::Result<String> {
    let yaml = serde_yaml::to_string(value).context("while emitting pipeline yaml")?;
    Ok(format!("{GENERATED_YAML_HEADER}{yaml}"))
}

