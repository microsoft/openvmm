#[derive(Debug)]
pub(crate) enum FloweySource {
    // bool indicates if this node should publish the flowey it bootstraps for
    // other nodes to consume
    Bootstrap(String, bool),
    Consume(String),
}

/// each job has one of three "roles" when it comes to bootstrapping flowey:
///
/// 1. Build flowey
/// 2. Building _and_ publishing flowey
/// 3. Consuming a pre-built flowey
///
/// We _could_ just have every bootstrap job also publish flowey, but this
/// will spam the artifact feed with artifacts no one will consume, which is
/// wasteful.
///
/// META: why go through all this hassle anyways? i.e: why not just do
/// something dead simple like:
///
/// - discover which platforms exist in the graph
/// - have the first jobs of every pipeline be standalone "bootstrap flowey"
///   jobs, which all subsequent jobs of a certain platform can take a dep on
///
/// well... it turns out that provisioning job runners is _sloooooow_,
/// and having every single pipeline run these "bootstrap flowey" steps
/// gating the rest of the "interesting" stuff would really stink.
///
/// i.e: it's better to do redundant flowey bootstraps if it means that we
/// can avoid the extra time it takes to tear down + re-provision a worker.
pub(crate) fn job_flowey_bootstrap_source(
    graph: &petgraph::Graph<ResolvedPipelineJob, ()>,
    order: &Vec<petgraph::prelude::NodeIndex>,
) -> BTreeMap<petgraph::prelude::NodeIndex, FloweySource> {
    let mut bootstrapped_flowey = BTreeMap::new();

    // the first traversal builds a list of all ancestors of a give node
    let mut ancestors = BTreeMap::<
        petgraph::prelude::NodeIndex,
        BTreeSet<(petgraph::prelude::NodeIndex, FlowPlatform, FlowArch)>,
    >::new();
    for idx in order {
        for ancestor_idx in graph
            .edges_directed(*idx, petgraph::Direction::Incoming)
            .map(|e| e.source())
        {
            ancestors.entry(*idx).or_default().insert((
                ancestor_idx,
                graph[ancestor_idx].platform,
                graph[ancestor_idx].arch,
            ));

            if let Some(set) = ancestors.get(&ancestor_idx).cloned() {
                ancestors.get_mut(idx).unwrap().extend(&set);
            }
        }
    }

    // the second traversal assigns roles to each node
    let mut floweyno = 0;
    'outer: for idx in order {
        let ancestors = ancestors.remove(idx).unwrap_or_default();

        let mut elect_bootstrap = None;

        for (ancestor_idx, platform, arch) in ancestors {
            if platform != graph[*idx].platform || arch != graph[*idx].arch {
                continue;
            }

            let role =
                bootstrapped_flowey
                    .get_mut(&ancestor_idx)
                    .and_then(|existing| match existing {
                        FloweySource::Bootstrap(s, true) => Some(FloweySource::Consume(s.clone())),
                        FloweySource::Consume(s) => Some(FloweySource::Consume(s.clone())),
                        // there is an ancestor that is building, but not
                        // publishing. maybe they should get upgraded...
                        FloweySource::Bootstrap(_, false) => {
                            elect_bootstrap = Some(ancestor_idx);
                            None
                        }
                    });

            if let Some(role) = role {
                bootstrapped_flowey.insert(*idx, role);
                continue 'outer;
            }
        }

        // if we got here, that means we couldn't find a valid ancestor.
        //
        // check if we can upgrade an existing ancestor vs. bootstrapping
        // things ourselves
        if let Some(elect_bootstrap) = elect_bootstrap {
            let FloweySource::Bootstrap(s, publish) =
                bootstrapped_flowey.get_mut(&elect_bootstrap).unwrap()
            else {
                unreachable!()
            };

            *publish = true;
            let s = s.clone();

            bootstrapped_flowey.insert(*idx, FloweySource::Consume(s));
        } else {
            // Having this extra unique `floweyno` per bootstrap is
            // necessary since GitHub doesn't let you double-publish an
            // artifact with the same name
            floweyno += 1;
            let platform = graph[*idx].platform;
            let arch = graph[*idx].arch;
            bootstrapped_flowey.insert(
                *idx,
                FloweySource::Bootstrap(
                    format!("_internal-flowey-bootstrap-{arch}-{platform}-uid-{floweyno}"),
                    false,
                ),
            );
        }
    }

    bootstrapped_flowey
}

/// Regenerate YAML or check the root pipeline and all generated templates.
/// Runtime mode writes the database JSON only after every YAML file matches.
fn check_or_write_generated_yaml_and_json<T>(
    pipeline: &T,
    pipeline_static_db: &FloweyPipelineStaticDb,
    mode: CheckMode,
    repo_root: &Path,
    pipeline_file: &Path,
    ado_post_process_yaml_cb: Option<Box<dyn FnOnce(Value) -> Value>>,
    ado_job_templates: bool,
) -> anyhow::Result<()>
where
    T: Serialize,
{
    let generated_yaml =
        serde_yaml::to_value(pipeline).context("while serializing pipeline yaml")?;
    let mut generated_yaml = if let Some(ado_post_process_yaml_cb) = ado_post_process_yaml_cb {
        ado_post_process_yaml_cb(generated_yaml)
    } else {
        generated_yaml
    };

    let mut files = if ado_job_templates {
        super::ado_yaml_templates::extract_jobs(&mut generated_yaml, pipeline_file)?
    } else {
        BTreeMap::new()
    };
    files.insert(pipeline_file.to_owned(), serialize_yaml(&generated_yaml)?);

    for (path, yaml) in &files {
        check_generated_yaml_size(yaml, pipeline_static_db.flow_backend, path)?;
    }

    check_or_write_yaml_files(
        &files,
        &mode,
        pipeline_static_db.flow_backend,
        repo_root,
        pipeline_file,
    )?;

    if let CheckMode::Runtime(check_file) = mode {
        let generated_json = serde_json::to_string_pretty(pipeline_static_db)
            .context("while emitting pipeline json")?;
        let mut f = fs_err::File::create(check_file.with_extension("json"))?;
        f.write_all(generated_json.as_bytes())
            .context("while emitting pipeline database json")?;
    }

    Ok(())
}

fn check_or_write_yaml_files(
    files: &BTreeMap<PathBuf, String>,
    mode: &CheckMode,
    backend: FlowBackendCli,
    repo_root: &Path,
    pipeline_file: &Path,
) -> anyhow::Result<()> {
    let output_path = |path: &Path| -> PathBuf {
        match mode {
            CheckMode::Runtime(check_file) if path == pipeline_file => check_file.clone(),
            CheckMode::Check(check_file) => {
                if path == pipeline_file {
                    check_file.clone()
                } else {
                    check_file
                        .parent()
                        .unwrap_or(Path::new(""))
                        .join(path.strip_prefix(pipeline_file.parent().unwrap()).unwrap())
                }
            }
            CheckMode::None | CheckMode::Runtime(_) => repo_root.join(path),
        }
    };
    let stale = if matches!(backend, FlowBackendCli::Ado) {
        // The bootstrap root is a snapshot, but its templates remain in the
        // checkout where the bootstrap binary is built.
        let directory = match mode {
            CheckMode::Check(check_file) => check_file.parent().unwrap().to_owned(),
            CheckMode::None | CheckMode::Runtime(_) => {
                repo_root.join(pipeline_file.parent().unwrap())
            }
        };
        super::ado_yaml_templates::stale_templates(
            pipeline_file,
            &directory,
            &files.keys().map(|path| output_path(path)).collect(),
        )?
    } else {
        Vec::new()
    };

    if !matches!(mode, CheckMode::None) {
        for (path, generated_yaml) in files {
            let path = output_path(path);
            let existing_yaml = fs_err::read_to_string(&path)
                .with_context(|| format!("cannot check YAML file '{}'", path.display()))?;

            if existing_yaml != *generated_yaml {
                println!(
                    "generated yaml {}:\n==========\n{generated_yaml}",
                    generated_yaml.len()
                );
                println!(
                    "existing yaml {}:\n==========\n{existing_yaml}",
                    existing_yaml.len()
                );
                anyhow::bail!(
                    "checked in YAML '{}' is out of date! run `cargo xflowey regen`",
                    path.display(),
                )
            }
        }
        if let Some(path) = stale.first() {
            anyhow::bail!(
                "stale generated YAML template '{}'; run `cargo xflowey regen`",
                path.display(),
            );
        }
    } else {
        for (path, yaml) in files {
            let path = output_path(path);
            fs_err::create_dir_all(path.parent().unwrap())?;
            fs_err::write(path, yaml).context("while emitting pipeline yaml")?;
        }
        for path in stale {
            fs_err::remove_file(path)?;
        }
    }
    Ok(())
}

/// See [`check_or_write_generated_yaml_and_json`]
pub(crate) fn check_generated_yaml_and_json<T>(
    pipeline: &T,
    pipeline_static_db: &FloweyPipelineStaticDb,
    check: CheckMode,
    repo_root: &Path,
    pipeline_file: &Path,
    ado_post_process_yaml_cb: Option<Box<dyn FnOnce(Value) -> Value>>,
    ado_job_templates: bool,
) -> anyhow::Result<()>
where
    T: Serialize,
{
    check_or_write_generated_yaml_and_json(
        pipeline,
        pipeline_static_db,
        check,
        repo_root,
        pipeline_file,
        ado_post_process_yaml_cb,
        ado_job_templates,
    )
}

/// See [`check_or_write_generated_yaml_and_json`]
pub(crate) fn write_generated_yaml_and_json<T>(
    pipeline: &T,
    pipeline_static_db: &FloweyPipelineStaticDb,
    repo_root: &Path,
    pipeline_file: &Path,
    ado_post_process_yaml_cb: Option<Box<dyn FnOnce(Value) -> Value>>,
    ado_job_templates: bool,
) -> anyhow::Result<()>
where
    T: Serialize,
{
    check_or_write_generated_yaml_and_json(
        pipeline,
        pipeline_static_db,
        CheckMode::None,
        repo_root,
        pipeline_file,
        ado_post_process_yaml_cb,
        ado_job_templates,
    )
}

/// Merges a list of bash commands into a single YAML step.
pub(crate) struct BashCommands {
    commands: Vec<BashCommand>,
    label: Option<String>,
    can_merge: bool,
    github: bool,
}

enum BashCommand {
    Script(String),
    ExecSnippet {
        flowey_bin: String,
        node_modpath: String,
        snippet_idx: usize,
        job_idx: usize,
    },
}

impl BashCommands {
    pub fn new_github() -> Self {
        Self {
            commands: Vec::new(),
            label: None,
            can_merge: true,
            github: true,
        }
    }

    pub fn new_ado() -> Self {
        Self {
            commands: Vec::new(),
            label: None,
            can_merge: true,
            github: false,
        }
    }

    #[must_use]
    pub fn push(
        &mut self,
        label: Option<String>,
        can_merge: bool,
        mut cmd: String,
    ) -> Option<Value> {
        cmd.truncate(cmd.trim_end().len());
        self.push_command(label, can_merge, BashCommand::Script(cmd))
    }

    #[must_use]
    pub fn push_exec_snippet(
        &mut self,
        label: Option<String>,
        can_merge: bool,
        flowey_bin: &str,
        node_modpath: &str,
        snippet_idx: usize,
        job_idx: usize,
    ) -> Option<Value> {
        self.push_command(
            label,
            can_merge,
            BashCommand::ExecSnippet {
                flowey_bin: flowey_bin.into(),
                node_modpath: node_modpath.into(),
                snippet_idx,
                job_idx,
            },
        )
    }

    fn push_command(
        &mut self,
        label: Option<String>,
        can_merge: bool,
        cmd: BashCommand,
    ) -> Option<Value> {
        let val = if !can_merge && !self.can_merge {
            self.flush()
        } else {
            None
        };
        if !can_merge || self.label.is_none() {
            self.label = label;
        }
        self.commands.push(cmd);
        self.can_merge &= can_merge;
        val
    }

    pub fn push_minor(&mut self, cmd: String) {
        assert!(self.push(None, true, cmd).is_none());
    }

    fn render_commands(&self) -> String {
        let mut commands: Vec<String> = Vec::new();
        let mut previous_snippet = None;

        for command in &self.commands {
            match command {
                BashCommand::Script(script) => {
                    commands.push(script.clone());
                    previous_snippet = None;
                }
                BashCommand::ExecSnippet {
                    flowey_bin,
                    node_modpath,
                    snippet_idx,
                    job_idx,
                } => {
                    if previous_snippet == Some((flowey_bin.as_str(), *job_idx)) {
                        let command = commands.last_mut().unwrap();
                        command.push_str(&format!(" {node_modpath} {snippet_idx}"));
                    } else {
                        commands.push(construct_exec_snippet_cli(
                            flowey_bin,
                            node_modpath,
                            *snippet_idx,
                            *job_idx,
                        ));
                    }
                    previous_snippet = Some((flowey_bin.as_str(), *job_idx));
                }
            }
        }

        commands.join("\n")
    }

    #[must_use]
    pub fn flush(&mut self) -> Option<Value> {
        if self.commands.is_empty() {
            return None;
        }
        let label = if self.commands.len() == 1 || !self.can_merge {
            self.label.take()
        } else {
            None
        };
        let label = label.unwrap_or_else(|| "🦀 flowey rust steps".into());
        let commands = self.render_commands();
        let map = if self.github {
            serde_yaml::Mapping::from_iter([
                ("name".into(), label.into()),
                ("run".into(), commands.into()),
                ("shell".into(), "bash".into()),
            ])
        } else {
            let commands = if self.commands.len() == 1 {
                commands
            } else {
                // ADO doesn't automatically fail on error on multi-line scripts.
                format!("set -e\n{commands}")
            };
            serde_yaml::Mapping::from_iter([
                ("bash".into(), commands.into()),
                ("displayName".into(), label.into()),
            ])
        };
        self.commands.clear();
        self.can_merge = true;
        Some(map.into())
    }
}

