    #[test]
    fn template_checks_are_read_only_and_runtime_validates_before_writing_json() {
        let directory = tempfile::tempdir().unwrap();
        let path = Path::new("ci/example.yaml");
        let root = directory.path().join(path);
        let template = directory.path().join("ci/example.job-0.yaml");
        let pipeline: Value =
            serde_yaml::from_str("jobs:\n- job: build\n  steps:\n  - bash: echo hello").unwrap();
        let db = database();
        let generate = |mode| {
            check_or_write_generated_yaml_and_json(
                &pipeline,
                &db,
                mode,
                directory.path(),
                path,
                None,
                true,
            )
        };
        generate(CheckMode::None).unwrap();
        let original_root = fs_err::read(&root).unwrap();
        let original_template = fs_err::read(&template).unwrap();
        generate(CheckMode::Check(root.clone())).unwrap();
        assert!(!root.with_extension("json").exists());
        let relocated = directory.path().join("relocated/renamed.yaml");
        fs_err::create_dir(relocated.parent().unwrap()).unwrap();
        fs_err::copy(&root, &relocated).unwrap();
        fs_err::copy(&template, relocated.with_file_name("example.job-0.yaml")).unwrap();
        generate(CheckMode::Check(relocated)).unwrap();

        fs_err::write(&template, "changed").unwrap();
        let error = generate(CheckMode::Check(root.clone())).unwrap_err();
        assert!(format!("{error:#}").contains("example.job-0.yaml"));
        assert!(generate(CheckMode::Runtime(root.clone())).is_err());
        assert_eq!(fs_err::read_to_string(&template).unwrap(), "changed");
        assert!(!root.with_extension("json").exists());
        fs_err::remove_file(&template).unwrap();
        assert!(generate(CheckMode::Check(root.clone())).is_err());
        assert!(!template.exists());
        generate(CheckMode::None).unwrap();

        let stale = template.with_file_name("example.job-99.yaml");
        let unrelated = template.with_file_name("notes.yaml");
        let other_pipeline = template.with_file_name("example.job-98.yaml");
        fs_err::write(&stale, &original_template).unwrap();
        fs_err::write(&unrelated, "user content").unwrap();
        fs_err::write(
            &other_pipeline,
            format!("{GENERATED_YAML_HEADER}jobs: []\n"),
        )
        .unwrap();
        assert!(generate(CheckMode::Check(root.clone())).is_err());
        assert!(stale.exists());
        generate(CheckMode::None).unwrap();
        assert!(!stale.exists());
        assert_eq!(fs_err::read_to_string(unrelated).unwrap(), "user content");
        assert!(other_pipeline.exists());
        let bootstrap = directory.path().join("bootstrap/pipeline.yaml");
        fs_err::create_dir(bootstrap.parent().unwrap()).unwrap();
        fs_err::copy(&root, &bootstrap).unwrap();
        generate(CheckMode::Runtime(bootstrap.clone())).unwrap();
        let runtime: Value =
            serde_yaml::from_slice(&fs_err::read(bootstrap.with_extension("json")).unwrap())
                .unwrap();
        assert_eq!(runtime["flow_backend"], "Ado");
        assert_eq!(fs_err::read(&root).unwrap(), original_root);
        assert_eq!(fs_err::read(&template).unwrap(), original_template);

        let original_json = fs_err::read(bootstrap.with_extension("json")).unwrap();
        fs_err::write(&template, "changed template").unwrap();
        assert!(generate(CheckMode::Runtime(bootstrap.clone())).is_err());
        assert_eq!(
            fs_err::read(bootstrap.with_extension("json")).unwrap(),
            original_json
        );
        generate(CheckMode::None).unwrap();
        fs_err::write(&bootstrap, "changed root").unwrap();
        assert!(generate(CheckMode::Runtime(bootstrap.clone())).is_err());
        assert_eq!(fs_err::read_to_string(bootstrap).unwrap(), "changed root");
    }

    #[test]
    fn large_pipelines_split_but_individual_files_still_obey_the_byte_limit() {
        let directory = tempfile::tempdir().unwrap();
        let path = Path::new("example.yaml");
        let mut pipeline: Value = serde_yaml::from_str(
            "jobs:\n- job: first\n  steps: [{bash: echo}]\n- job: second\n  steps: [{bash: echo}]",
        )
        .unwrap();
        for job in pipeline["jobs"].as_sequence_mut().unwrap() {
            job["steps"][0]["bash"] = "é".repeat(150_000).into();
        }
        let db = database();
        let generate = |pipeline: &Value, templates| {
            check_or_write_generated_yaml_and_json(
                pipeline,
                &db,
                CheckMode::None,
                directory.path(),
                path,
                None,
                templates,
            )
        };
        assert!(generate(&pipeline, false).is_err());
        assert!(!directory.path().join(path).exists());
        generate(&pipeline, true).unwrap();
        for file in ["example.yaml", "example.job-0.yaml", "example.job-1.yaml"] {
            assert!(fs_err::metadata(directory.path().join(file)).unwrap().len() <= 524_288);
        }
        let mut oversized = pipeline.clone();
        oversized["jobs"][0]["steps"][0]["bash"] = "x".repeat(524_288).into();
        let error = generate(&oversized, true).unwrap_err();
        assert!(format!("{error:#}").contains("example.job-0.yaml"));
        oversized = pipeline.clone();
        oversized["variables"] = Value::Mapping(Mapping::from_iter([(
            "large".into(),
            "x".repeat(524_288).into(),
        )]));
        assert!(generate(&oversized, true).is_err());
    }

